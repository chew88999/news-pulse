// Measures each narration clip, checks it fits its slot, and writes the subtitles:
//   subtitles.js           → loaded by promo.html for the burned-in captions
//   news-pulse-promo.srt   → sidecar file, also embedded in the MP4 as a subtitle track
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ffmpegPath from "ffmpeg-static";

const here = fileURLToPath(new URL(".", import.meta.url));
const { lines } = JSON.parse(readFileSync(`${here}narration.json`, "utf8"));
const MAX_CHARS = 74; // per caption, so it fits on one line at the bottom

/** Clip length, plus the silence the voice adds at the start, and the length of the actual speech (ms). */
function analyse(file) {
  const res = spawnSync(ffmpegPath, ["-hide_banner", "-i", file, "-af", "silencedetect=noise=-40dB:d=0.08", "-f", "null", "-"], { encoding: "utf8" });
  const log = res.stderr;
  const [, h, m, s] = /Duration: (\d+):(\d+):([\d.]+)/.exec(log);
  const total = (Number(h) * 3600 + Number(m) * 60 + Number(s)) * 1000;
  const starts = [...log.matchAll(/silence_start: ([\d.]+)/g)].map((x) => Number(x[1]) * 1000);
  const ends = [...log.matchAll(/silence_end: ([\d.]+)/g)].map((x) => Number(x[1]) * 1000);
  // Leading silence: a silence that starts at ~0. Trailing silence: the last one, if it runs to the end.
  const lead = starts.length && starts[0] < 30 ? ends[0] ?? 0 : 0;
  const lastStart = starts.at(-1);
  const trail = lastStart !== undefined && (ends.length < starts.length || total - ends.at(-1) < 30) ? total - lastStart : 0;
  return { total, lead, speech: total - lead - trail };
}

/** Splits a line into captions of at most MAX_CHARS, preferring sentence and clause breaks. */
function chunk(text) {
  const parts = text.match(/[^.?!:]+[.?!:]?/g).map((s) => s.trim()).filter(Boolean);
  const out = [];
  for (const part of parts) {
    if (part.length <= MAX_CHARS) { out.push(part); continue; }
    // Prefer breaking at the comma closest to the middle, so each caption is a whole phrase.
    const commas = [...part.matchAll(/, /g)].map((m) => m.index + 1).filter((i) => i <= MAX_CHARS && part.length - i <= MAX_CHARS);
    if (commas.length) {
      const at = commas.reduce((best, i) => (Math.abs(i - part.length / 2) < Math.abs(best - part.length / 2) ? i : best));
      out.push(part.slice(0, at).trim(), part.slice(at).trim());
      continue;
    }
    let cur = "";
    for (const word of part.split(" ")) {
      if ((cur + " " + word).trim().length > MAX_CHARS) { out.push(cur.trim()); cur = word; }
      else cur += " " + word;
    }
    if (cur.trim()) out.push(cur.trim());
  }
  // Merge very short neighbours ("Checked.") so captions don't flicker.
  const merged = [];
  for (const c of out) {
    const prev = merged.at(-1);
    if (prev && (prev.length < 22 || c.length < 14) && (prev + " " + c).length <= MAX_CHARS) merged[merged.length - 1] = prev + " " + c;
    else merged.push(c);
  }
  return merged;
}

const subs = [];
let ok = true;
for (const line of lines) {
  const a = analyse(`${here}voice/${line.id}.wav`);
  const speakFrom = line.start + a.lead;
  const speakTo = speakFrom + a.speech;
  // Trailing silence may overlap the next line; only the speech itself must fit the slot.
  const fits = speakTo <= line.end;
  if (!fits) ok = false;
  console.log(`${line.id}  speech ${(a.speech / 1000).toFixed(2)}s  ends ${(speakTo / 1000).toFixed(2)}s  slot ends ${(line.end / 1000).toFixed(2)}s  ${fits ? "ok" : "TOO LONG by " + ((speakTo - line.end) / 1000).toFixed(2) + "s"}`);

  const captions = chunk(line.text);
  const totalChars = captions.reduce((n, c) => n + c.length, 0);
  let t = speakFrom;
  captions.forEach((c, i) => {
    const dur = (a.speech * c.length) / totalChars;
    const isLast = i === captions.length - 1;
    subs.push({ start: Math.round(t), end: Math.round(isLast ? Math.min(speakTo + 500, line.end) : t + dur), text: c });
    t += dur;
  });
}

writeFileSync(`${here}subtitles.js`, `// Generated by subtitles.mjs from narration.json; do not edit by hand.\nwindow.SUBTITLES = ${JSON.stringify(subs, null, 1)};\n`);
const ts = (ms) => {
  const h = Math.floor(ms / 3600000), m = Math.floor((ms % 3600000) / 60000), s = Math.floor((ms % 60000) / 1000);
  return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")},${String(ms % 1000).padStart(3, "0")}`;
};
writeFileSync(`${here}news-pulse-promo.srt`, subs.map((s, i) => `${i + 1}\n${ts(s.start)} --> ${ts(s.end)}\n${s.text}\n`).join("\n"));
console.log(`${subs.length} captions → subtitles.js, news-pulse-promo.srt`);
if (!ok) {
  console.error("Some lines are longer than their slot: shorten the text or raise \"rate\" in narration.json, then rerun voice.ps1.");
  process.exit(1);
}
